# Loose initial-geometry cutoffs for both nanoparticles and slabs.
# Initial configurations are generated by placing adsorbates according to
# prescribed top, bridge, or hollow motifs. Slightly relaxed distance
# cutoffs therefore account for deviations from ideal bond lengths before
# DFT relaxation, while recovering the intended anchoring environment.
#
# A distance-based criterion is preferred over reconstructing the motif
# from geometric features (e.g., bridge midpoints or hollow centroids).
# Although these features are well defined during motif construction on
# the bare catalyst, their inverse identification can be ambiguous on
# curved, irregular, or non-planar surfaces, where local surface normals
# and neighboring atomic arrangements are not uniquely defined.
#
# Periodic slabs use minimum-image distances.
NI_O_CUTOFF_INITIAL = 2.45
NI_H_CUTOFF_INITIAL = 2.10

NI_O_CUTOFF_INITIAL = 2.45
