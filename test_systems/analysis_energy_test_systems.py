#!/usr/bin/env python3
"""Validate M6 on the five external Ni test systems and make paper figures.

Expected directories beside this script:
    Ni55, Ni91, Ni130, Ni111_4x3, Ni100_4x4

Each directory contains one ``*_ranked_candidates.csv`` file, ``ini_xyz``,
``opt_xyz``, ``inference_ene.txt``, ``ref_en_slab.txt``, and
``ref_en_H2O.txt``.

The ranked-candidate CSV supplies predicted adsorption energies and retention
scores. DFT adsorption energies must come from a DFT_Eads_eV column in the CSV,
or from inference_ene.txt, ref_en_slab.txt (bare Ni energy), and ref_en_H2O.txt
(the latter three use Ry). The only figure outputs are the combined 2x5
absolute/relative-energy parity figure and the two-row ranking figure.

Initial motifs are reconstructed from geometry using loose adsorbate cutoffs
plus connected Ni-anchor topology; neither filename motifs nor extxyz metadata
bias the assignment. For periodic slabs, both adsorbate--Ni contacts and Ni--Ni
anchor connectivity are evaluated with minimum-image distances from the cell
and PBC information. Relaxed slab contacts use the same minimum-image treatment.
"""

