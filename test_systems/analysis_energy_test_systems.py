def read_first_float(path: Path) -> float:
    with path.open() as handle:
        for line in handle:
            line = line.strip()
            if line and not line.startswith("#"):
                return float(line.split()[0])
    raise ValueError(f"No numeric value found in {path}")


def _parse_lattice(comment: str) -> np.ndarray | None:
    match = re.search(r'Lattice\s*=\s*"([^"]+)"', comment, re.IGNORECASE)
    if match:
        values = [float(value) for value in match.group(1).split()]
        if len(values) == 9:
            return np.asarray(values, dtype=float).reshape(3, 3)
    return None


def _parse_pbc(comment: str, cell: np.ndarray | None) -> np.ndarray:
    match = re.search(r'pbc\s*=\s*"([^"]+)"', comment, re.IGNORECASE)
    if not match:
        return np.asarray([cell is not None] * 3, dtype=bool)
    tokens = match.group(1).replace(",", " ").split()
    if len(tokens) != 3:
        return np.asarray([cell is not None] * 3, dtype=bool)
    true_tokens = {"t", "true", "1", "yes", "y"}
    false_tokens = {"f", "false", "0", "no", "n"}
    parsed: list[bool] = []
    for token in tokens:
        key = token.lower()
        if key in true_tokens:
            parsed.append(True)
        elif key in false_tokens:
            parsed.append(False)
        else:
            return np.asarray([cell is not None] * 3, dtype=bool)
    return np.asarray(parsed, dtype=bool)


def read_xyz(path: Path) -> tuple[list[str], np.ndarray, np.ndarray | None, np.ndarray, str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    if len(lines) < 2:
        raise ValueError(f"Malformed XYZ: {path}")
    n_atoms = int(lines[0].strip())
    comment = lines[1]
    cell = _parse_lattice(comment)
    pbc = _parse_pbc(comment, cell)
    symbols: list[str] = []
    positions: list[list[float]] = []
    for line in lines[2 : 2 + n_atoms]:
        fields = line.split()
        symbols.append(fields[0])
        positions.append([float(fields[1]), float(fields[2]), float(fields[3])])
    if len(symbols) != n_atoms:
        raise ValueError(f"Expected {n_atoms} atoms but read {len(symbols)} from {path}")
    return symbols, np.asarray(positions, dtype=float), cell, pbc, comment


def _mic_distances(
    reference: np.ndarray,
    queries: np.ndarray,
    cell: np.ndarray | None,
    pbc: np.ndarray | None,
) -> np.ndarray:
    delta = np.asarray(queries, dtype=float) - np.asarray(reference, dtype=float)
    if cell is None or pbc is None or not np.any(pbc):
        return np.linalg.norm(delta, axis=1)
    fractional = delta @ np.linalg.inv(cell)
    fractional[:, pbc] -= np.round(fractional[:, pbc])
    return np.linalg.norm(fractional @ cell, axis=1)


def _mic_distance(
    position_a: np.ndarray,
    position_b: np.ndarray,
    cell: np.ndarray | None,
    pbc: np.ndarray | None,
) -> float:
    return float(_mic_distances(position_a, np.asarray([position_b]), cell, pbc)[0])


def classify_site(n_anchors: int) -> str:
    if n_anchors <= 1:
        return "T"
    if n_anchors == 2:
        return "B"
    if n_anchors == 3:
        return "H"
    if n_anchors == 4:
        return "F"
    raise ValueError(f"Unexpected coordination: {n_anchors}")


def _ni_atoms_are_bonded(
    index_a: int,
    index_b: int,
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> bool:
    return bool(
        _mic_distance(positions[index_a], positions[index_b], cell, pbc)
        < NI_NI_ANCHOR_CUTOFF
    )


def _is_valid_initial_hollow(
    anchors: tuple[int, ...],
    ni_indices: list[int],
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> bool:
    """Accept a Ni triangle or a hollow obtained from a chordless 4-ring."""
    degrees = {index: 0 for index in anchors}
    n_bonds = 0
    for index_a, index_b in combinations(anchors, 2):
        if _ni_atoms_are_bonded(index_a, index_b, positions, cell, pbc):
            degrees[index_a] += 1
            degrees[index_b] += 1
            n_bonds += 1

    if n_bonds == 3:
        return True
    if n_bonds != 2 or sorted(degrees.values()) != [1, 1, 2]:
        return False

    center = next(index for index, degree in degrees.items() if degree == 2)
    endpoints = [index for index, degree in degrees.items() if degree == 1]
    return any(
        missing not in anchors
        and _ni_atoms_are_bonded(missing, endpoints[0], positions, cell, pbc)
        and _ni_atoms_are_bonded(missing, endpoints[1], positions, cell, pbc)
        and not _ni_atoms_are_bonded(missing, center, positions, cell, pbc)
        for missing in ni_indices
    )


def _is_valid_initial_fourfold(
    anchors: tuple[int, ...],
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> bool:
    """Require every atom in a fourfold anchor set to have two Ni neighbors."""
    degrees = {index: 0 for index in anchors}
    for index_a, index_b in combinations(anchors, 2):
        if _ni_atoms_are_bonded(index_a, index_b, positions, cell, pbc):
            degrees[index_a] += 1
            degrees[index_b] += 1
    return min(degrees.values()) >= 2


def _select_topological_initial_anchors(
    candidates: list[tuple[int, float]],
    ni_indices: list[int],
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> list[tuple[int, float]]:
    """Infer T/B/H/F anchors from adsorbate contacts and Ni bond topology."""
    ordered = sorted(candidates, key=lambda item: (item[1], item[0]))
    distance_by_index = {index: distance for index, distance in ordered}

    for count in range(min(MAX_ANCHORS_PER_ADSORBATE, len(ordered)), 0, -1):
        valid: list[
            tuple[tuple[int, float, tuple[float, ...], tuple[int, ...]], tuple[int, ...]]
        ] = []
        for subset in combinations((index for index, _ in ordered), count):
            if count == 4:
                is_valid = _is_valid_initial_fourfold(
                    subset, positions, cell, pbc
                )
            elif count == 3:
                is_valid = _is_valid_initial_hollow(
                    subset, ni_indices, positions, cell, pbc
                )
            elif count == 2:
                is_valid = _ni_atoms_are_bonded(
                    subset[0], subset[1], positions, cell, pbc
                )
            else:
                is_valid = True
            if not is_valid:
                continue

            n_bonds = sum(
                _ni_atoms_are_bonded(index_a, index_b, positions, cell, pbc)
                for index_a, index_b in combinations(subset, 2)
            )
            distances = tuple(sorted(distance_by_index[index] for index in subset))
            key = (-n_bonds, sum(distances), distances, tuple(sorted(subset)))
            valid.append((key, subset))

        if valid:
            _, selected = min(valid, key=lambda item: item[0])
            return sorted(
                ((index, distance_by_index[index]) for index in selected),
                key=lambda item: (item[1], item[0]),
            )
    return []


def _extract_hybrid_anchor_set(
    ni_indices: list[int],
    distances: np.ndarray,
    short_cutoff: float,
    extended_cutoff: float,
    folded_n_short: int,
    folded_n_total: int,
    max_standard_anchors: int,
) -> tuple[str, frozenset[int]]:
    extended = sorted(
        (
            (int(index), float(distance))
            for index, distance in zip(ni_indices, distances)
            if float(distance) < extended_cutoff
        ),
        key=lambda item: item[1],
    )
    short = [item for item in extended if item[1] < short_cutoff]
    if len(short) >= folded_n_short and len(extended) == folded_n_total:
        selected = extended[:folded_n_total]
        site_type = "F"
    else:
        selected = short[:max_standard_anchors]
        site_type = classify_site(len(selected))
    return site_type, frozenset(index for index, _ in selected)


def _adsorbate_positions(
    symbols: list[str],
    positions: np.ndarray,
    cell: np.ndarray | None,
    pbc: np.ndarray | None,
) -> tuple[list[int], np.ndarray, np.ndarray]:
    ni_indices = [index for index, symbol in enumerate(symbols) if symbol == "Ni"]
    o_indices = [index for index, symbol in enumerate(symbols) if symbol == "O"]
    h_indices = [index for index, symbol in enumerate(symbols) if symbol == "H"]
    if len(o_indices) != 1 or len(h_indices) != 2:
        raise ValueError(f"Unexpected composition: {len(o_indices)} O and {len(h_indices)} H")
    o_position = positions[o_indices[0]]
    h_distances = sorted(
        (
            (index, _mic_distance(o_position, positions[index], cell, pbc))
            for index in h_indices
        ),
        key=lambda item: item[1],
    )
    if h_distances[0][1] > OH_CUTOFF:
        raise ValueError(f"O-H distance {h_distances[0][1]:.3f} A > {OH_CUTOFF:.2f} A")
    return ni_indices, o_position, positions[h_distances[1][0]]


def get_final_site(
    symbols: list[str],
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> tuple[str, frozenset[int], frozenset[int]]:
    ni_indices, o_position, h_ads_position = _adsorbate_positions(
        symbols, positions, cell, pbc
    )
    ni_positions = positions[ni_indices]
    o_distances = _mic_distances(o_position, ni_positions, cell, pbc)
    h_distances = _mic_distances(h_ads_position, ni_positions, cell, pbc)
    o_type, o_anchors = _extract_hybrid_anchor_set(
        ni_indices,
        o_distances,
        NI_O_CUTOFF,
        NI_O_FOLDED_CUTOFF,
        O_FOLDED_N_SHORT,
        O_FOLDED_N_TOTAL,
        MAX_STANDARD_O_ANCHORS,
    )
    h_type, h_anchors = _extract_hybrid_anchor_set(
        ni_indices,
        h_distances,
        NI_H_CUTOFF,
        NI_H_FOLDED_CUTOFF,
        H_FOLDED_N_SHORT,
        H_FOLDED_N_TOTAL,
        MAX_STANDARD_H_ANCHORS,
    )
    if not o_anchors:
        raise ValueError(f"No Ni-O contact within {NI_O_CUTOFF:.2f} A")
    if not h_anchors:
        raise ValueError(f"No Ni-H contact within {NI_H_CUTOFF:.2f} A")
    return o_type + h_type, o_anchors, h_anchors


def _extract_initial_anchor_set(
    ni_indices: list[int],
    distances: np.ndarray,
    positions: np.ndarray,
    cutoff: float,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> tuple[str, frozenset[int]]:
    candidates = sorted(
        (
            (int(index), float(distance))
            for index, distance in zip(ni_indices, distances)
            if float(distance) < cutoff
        ),
        key=lambda item: item[1],
    )
    hits = _select_topological_initial_anchors(
        candidates, ni_indices, positions, cell, pbc
    )
    return classify_site(len(hits)), frozenset(index for index, _ in hits)


def get_initial_site(
    symbols: list[str],
    positions: np.ndarray,
    cell: np.ndarray | None = None,
    pbc: np.ndarray | None = None,
) -> tuple[str, frozenset[int], frozenset[int]]:
    ni_indices, o_position, h_ads_position = _adsorbate_positions(
        symbols, positions, cell, pbc
    )
    ni_positions = positions[ni_indices]
    o_type, o_anchors = _extract_initial_anchor_set(
        ni_indices,
        _mic_distances(o_position, ni_positions, cell, pbc),
        positions,
        NI_O_CUTOFF_INITIAL,
        cell,
        pbc,
    )
    h_type, h_anchors = _extract_initial_anchor_set(
        ni_indices,
        _mic_distances(h_ads_position, ni_positions, cell, pbc),
        positions,
        NI_H_CUTOFF_INITIAL,
        cell,
        pbc,
    )
    if not o_anchors or not h_anchors:
        raise ValueError("Initial loose-cutoff rule found an empty anchor set")
    return o_type + h_type, o_anchors, h_anchors


def read_inference_energies(path: Path) -> dict[int, float]:
    energies: dict[int, float] = {}
    current_config: int | None = None
    with path.open() as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line:
                continue
            if line.startswith("#"):
                match = re.search(r"conf?(\d+)", line)
                current_config = int(match.group(1)) if match else None
            elif current_config is not None:
                energies[current_config] = float(line.split()[0])
                current_config = None
    return energies


def parse_anchor_field(value: object) -> frozenset[int]:
    return frozenset(int(number) for number in re.findall(r"\d+", str(value)))


def build_candidate_lookup(df: pd.DataFrame) -> dict[tuple, pd.Series]:
    lookup: dict[tuple, pd.Series] = {}
    for _, row in df.sort_values("rank").iterrows():
        key = (
            str(row["motif"]),
            parse_anchor_field(row["o_anchor_idx"]),
            parse_anchor_field(row["h_anchor_idx"]),
        )
        lookup.setdefault(key, row)
    return lookup


def initial_files(system_dir: Path, kind: str) -> list[tuple[Path, int]]:
    """Find confXX_*.xyz files and retain only their integer identifiers."""
    result = []
    pattern = re.compile(r"^conf(?P<id>\d+)_[TBHF]{2}\.xyz$", re.I)
    directory = system_dir / "ini_xyz"
    if not directory.is_dir():
        raise FileNotFoundError(f"Initial-structure folder not found: {directory}")
    for path in directory.glob("*.xyz"):
        match = pattern.fullmatch(path.name)
        if match:
            result.append((path, int(match.group("id"))))
    return sorted(result, key=lambda item: (item[1], item[0].name))


def find_optimized_file(system_dir: Path, initial_path: Path, config: int, kind: str) -> Path | None:
    """Pair conf00_BH.xyz -> opt_xyz/conf00_opt.xyz (preserve leading zeroes)."""
    token = re.match(r"^conf(\d+)_", initial_path.name).group(1)
    candidates = [
        system_dir / "opt_xyz" / f"conf{token}_opt.xyz",
        system_dir / "opt_xyz" / f"conf{config}_opt.xyz",
    ]
    return next((path for path in candidates if path.is_file()), None)


def optional_dft_energies(system_dir: Path):
    """Read optional original DFT total-energy files; do not invent missing data."""
    file_paths = [system_dir / name for name in
                  ("inference_ene.txt", "ref_en_slab.txt", "ref_en_H2O.txt")]
    if all(path.is_file() for path in file_paths):
        inference = read_inference_energies(file_paths[0])
        bare_ev = read_first_float(file_paths[1]) * RY_TO_EV
        water_ev = read_first_float(file_paths[2]) * RY_TO_EV
        return inference, bare_ev, water_ev
    return {}, None, None


def dft_eads_from_csv(df: pd.DataFrame, config: int) -> float:
    """Optional direct Eads values, matched to the structure's configuration ID."""
    possible = ("DFT_Eads_eV", "dft_Eads_eV", "DFT_E_ads_eV", "Eads_DFT_eV")
    col = next((name for name in possible if name in df.columns), None)
    if col is None:
        return float("nan")
    if "conf" not in df.columns:
        # A full ranked-candidate CSV has candidate_id, not a mapping to
        # conf00, conf01, ... in the DFT validation folders.
        return float("nan")
    ids = pd.to_numeric(df["conf"], errors="coerce")
    matches = df.loc[ids == config, col]
    vals = pd.to_numeric(matches, errors="coerce").dropna().unique()
    return float(vals[0]) if len(vals) == 1 else float("nan")


def format_anchors(anchors: frozenset[int]) -> str:
    return ",".join(str(index) for index in sorted(anchors))


def process_system(root: Path, spec: SystemSpec) -> tuple[pd.DataFrame, list[str]]:
    system_dir = root / spec.folder
    csv_paths = sorted(system_dir.glob("*_ranked_candidates.csv"))
    if len(csv_paths) != 1:
        raise FileNotFoundError(
            f"{spec.label}: expected one *_ranked_candidates.csv file; "
            f"found {csv_paths}"
        )
    csv_path = csv_paths[0]
    candidates = pd.read_csv(csv_path)
    needed = {"motif", "o_anchor_idx", "h_anchor_idx", "rank", "pred_Eads_eV"}
    missing = needed.difference(candidates.columns)
    if missing:
        raise ValueError(f"{csv_path.name} missing columns {sorted(missing)}. "
                         f"Available columns: {list(candidates.columns)}")
    candidate_lookup = build_candidate_lookup(candidates)
    if "conf" not in candidates.columns:
        print("Using motif and O/H anchor sets to match ranked candidates; "
              "candidate_id is not the confXX XYZ file number.")
    inference, bare_ev, water_ev = optional_dft_energies(system_dir)
    if bare_ev is None and not any(name in candidates.columns for name in
        ("DFT_Eads_eV", "dft_Eads_eV", "DFT_E_ads_eV", "Eads_DFT_eV")):
        print("NOTE: No DFT energy source found. Retention can be analyzed, "
              "but parity plots require DFT_Eads_eV in the CSV, or "
              "inference_ene.txt + ref_en_slab.txt + ref_en_H2O.txt.")

    structures = initial_files(system_dir, spec.kind)
    if inference:
        structure_ids = {config for _, config in structures}
        energy_ids = set(inference)
        missing_energy_ids = sorted(structure_ids - energy_ids)
        unused_energy_ids = sorted(energy_ids - structure_ids)
        if missing_energy_ids or unused_energy_ids:
            raise ValueError(
                "Configuration IDs in inference_ene.txt do not match ini_xyz: "
                f"missing energies for {missing_energy_ids}; "
                f"unused energy entries {unused_energy_ids}"
            )

    rows: list[dict] = []
    errors: list[str] = []
    for ini_path, config in structures:
        opt_path = find_optimized_file(system_dir, ini_path, config, spec.kind)
        if opt_path is None:
            errors.append(f"config {config}: optimized XYZ not found")
            continue
        try:
            ini_symbols, ini_positions, ini_cell, ini_pbc, _ = read_xyz(ini_path)
            opt_symbols, opt_positions, opt_cell, opt_pbc, _ = read_xyz(opt_path)

            if spec.kind == "NP":
                initial_motif, initial_o, initial_h = get_initial_site(
                    ini_symbols, ini_positions
                )
                final_motif, final_o, final_h = get_final_site(
                    opt_symbols, opt_positions
                )
            else:
                initial_motif, initial_o, initial_h = get_initial_site(
                    ini_symbols, ini_positions, ini_cell, ini_pbc
                )
                final_motif, final_o, final_h = get_final_site(
                    opt_symbols, opt_positions, opt_cell, opt_pbc
                )

            actual_retained = (
                initial_motif == final_motif
                and initial_o == final_o
                and initial_h == final_h
            )

            initial_row = candidate_lookup.get((initial_motif, initial_o, initial_h))
            final_row = candidate_lookup.get((final_motif, final_o, final_h))

            retention_probability = np.nan
            retention_flag = "not found"
            initial_csv_rank = np.nan
            predicted_retained: bool | None = None
            retention_prediction_source = "not found"
            if initial_row is not None:
                initial_csv_rank = int(initial_row["rank"])
                retention_probability = pd.to_numeric(
                    initial_row.get(
                        "retention_probability",
                        initial_row.get("retention_score", np.nan),
                    ),
                    errors="coerce",
                )
                retention_flag = str(
                    initial_row.get(
                        "retention_flag",
                        initial_row.get("retention_class", "n/a"),
                    )
                )
                if pd.notna(retention_probability):
                    predicted_retained = bool(
                        float(retention_probability) >= spec.retention_threshold
                    )
                    retention_prediction_source = "ranking score"

            predicted_energy = (
                float(final_row["pred_Eads_eV"]) if final_row is not None else np.nan
            )
            final_csv_rank = int(final_row["rank"]) if final_row is not None else np.nan
            dft_energy = dft_eads_from_csv(candidates, config)
            if not np.isfinite(dft_energy) and config in inference and bare_ev is not None:
                dft_energy = inference[config] * RY_TO_EV - bare_ev - water_ev
            retention_correct = (
                predicted_retained == actual_retained
                if predicted_retained is not None
                else pd.NA
            )

            rows.append(
                {
                    "system": spec.label,
                    "system_type": spec.kind,
                    "config": config,
                    "initial_file": ini_path.name,
                    "optimized_file": opt_path.name,
                    "initial_motif": initial_motif,
                    "initial_o_anchor_idx": format_anchors(initial_o),
                    "initial_h_anchor_idx": format_anchors(initial_h),
                    "final_motif": final_motif,
                    "final_o_anchor_idx": format_anchors(final_o),
                    "final_h_anchor_idx": format_anchors(final_h),
                    "actual_retained": actual_retained,
                    "retention_threshold": spec.retention_threshold,
                    "retention_probability": retention_probability,
                    "ranking_retention_flag": retention_flag,
                    "predicted_retained": predicted_retained,
                    "retention_prediction_source": retention_prediction_source,
                    "retention_prediction_correct": retention_correct,
                    "initial_csv_rank": initial_csv_rank,
                    "final_csv_rank": final_csv_rank,
                    "DFT_Eads_eV": dft_energy,
                    "M6_Eads_eV": predicted_energy,
                }
            )
        except (ValueError, np.linalg.LinAlgError) as error:
            errors.append(f"config {config}: {error}")

    result = pd.DataFrame(rows)
    if result.empty:
        return result, errors

    paired = result.dropna(subset=["DFT_Eads_eV", "M6_Eads_eV"]).copy()
    result["DFT_rel_Eads_eV"] = np.nan
    result["M6_rel_Eads_eV"] = np.nan
    result["DFT_rank"] = np.nan
    result["M6_rank"] = np.nan
    if not paired.empty:
        reference_index = paired["DFT_Eads_eV"].idxmin()
        result.loc[paired.index, "DFT_rel_Eads_eV"] = (
            paired["DFT_Eads_eV"] - result.loc[reference_index, "DFT_Eads_eV"]
        )
        result.loc[paired.index, "M6_rel_Eads_eV"] = (
            paired["M6_Eads_eV"] - result.loc[reference_index, "M6_Eads_eV"]
        )
        result.loc[paired.index, "DFT_rank"] = rankdata(
            result.loc[paired.index, "DFT_rel_Eads_eV"], method="average"
        )
        result.loc[paired.index, "M6_rank"] = rankdata(
            result.loc[paired.index, "M6_rel_Eads_eV"], method="average"
        )
    return result.sort_values("config").reset_index(drop=True), errors


def print_initial_filename_motif_check(data: pd.DataFrame) -> None:
    """Report filename/geometry motif mismatches without affecting analysis."""
    print("\n" + "=" * 78)
    print("INITIAL MOTIF NAME CHECK (geometry-derived motifs)")
    print("=" * 78)
    print("Filename motif labels are used only in this diagnostic section.\n")

    for system, subset in data.groupby("system", sort=False):
        mismatches: list[tuple[str, str, str, str, str]] = []
        checked = 0
        for _, row in subset.iterrows():
            match = re.match(
                r"^conf\d+_([TBHF]{2})\.xyz$", str(row["initial_file"]), re.I
            )
            if match is None:
                continue
            checked += 1
            filename_motif = match.group(1).upper()
            geometry_motif = str(row["initial_motif"]).upper()
            if filename_motif != geometry_motif:
                mismatches.append(
                    (
                        str(row["initial_file"]),
                        filename_motif,
                        geometry_motif,
                        str(row["initial_o_anchor_idx"]),
                        str(row["initial_h_anchor_idx"]),
                    )
                )

        print(
            f"{system}: {checked - len(mismatches)}/{checked} filename motifs match "
            "the geometry-derived motifs."
        )
        if mismatches:
            print(
                f"  {'initial file':<24} {'name':>6} {'geometry':>10} "
                f"{'O anchors':>14} {'H anchors':>14}"
            )
            print("  " + "-" * 74)
            for filename, named, geometric, o_anchors, h_anchors in mismatches:
                print(
                    f"  {filename:<24} {named:>6} {geometric:>10} "
                    f"{o_anchors:>14} {h_anchors:>14}"
                )


def print_retention_summary(data: pd.DataFrame, specs: tuple[SystemSpec, ...]) -> None:
    print("\n" + "=" * 78)
    print("RETENTION PREDICTION (initial motif + exact O/H Ni anchor sets)")
    print("=" * 78)
    total_evaluated = 0
    total_correct = 0
    for spec in specs:
        subset = data[data["system"] == spec.label].copy()
        evaluable = subset[subset["predicted_retained"].notna()].copy()
        correct = int(evaluable["retention_prediction_correct"].astype(bool).sum())
        total = len(evaluable)
        total_evaluated += total
        total_correct += correct
        actual_retained = int(subset["actual_retained"].sum())
        predicted_retained = int(evaluable["predicted_retained"].astype(bool).sum())
        predicted_retained_rows = evaluable[
            evaluable["predicted_retained"].astype(bool)
        ]
        correctly_predicted_retained = int(
            predicted_retained_rows["actual_retained"].astype(bool).sum()
        )
        retained_precision = (
            100.0 * correctly_predicted_retained / predicted_retained
            if predicted_retained
            else float("nan")
        )
        unmatched = subset[subset["predicted_retained"].isna()]["config"].astype(int).tolist()
        incorrect = evaluable[
            ~evaluable["retention_prediction_correct"].astype(bool)
        ]["config"].astype(int).tolist()
        accuracy = 100.0 * correct / total if total else float("nan")
        print(
            f"\n=== {spec.label} [{spec.kind}] -- "
            f"s_ret >= {spec.retention_threshold:.2f} ===\n"
        )
        print(
            f"  {'initial file':<28}  {'init_rank_M6':>13}  "
            f"{'final_rank_M6':>14}  {'changed':>7}  {'correct':>7}"
        )
        separator = "  " + "-" * 82
        print(separator)
        for _, row in subset.iterrows():
            init_rank = (
                f"rank_{int(row['initial_csv_rank'])}"
                if pd.notna(row["initial_csv_rank"])
                else "not found"
            )
            final_rank = (
                f"rank_{int(row['final_csv_rank'])}"
                if pd.notna(row["final_csv_rank"])
                else "not found"
            )
            changed = "no" if bool(row["actual_retained"]) else "yes"
            if pd.isna(row["retention_prediction_correct"]):
                correct_text = "n/a"
            else:
                correct_text = "YES" if bool(row["retention_prediction_correct"]) else "NO"
            print(
                f"  {row['initial_file']:<28}  {init_rank:>13}  "
                f"{final_rank:>14}  {changed:>7}  {correct_text:>7}"
            )
        print(separator)
        print(
            f"  Prediction correct: {correct}/{total} ({accuracy:.1f}%) | "
            f"actual retained: {actual_retained} | "
            f"predicted retained: {predicted_retained}"
        )
        print(
            f"  Predicted retained that are actually retained: "
            f"{correctly_predicted_retained}/{predicted_retained} "
            f"({retained_precision:.1f}%)"
        )
        if incorrect:
            print(f"  Incorrect configs: {incorrect}")
        if unmatched:
            print(f"  Unmatched initial sites: {unmatched}")

    overall = 100.0 * total_correct / total_evaluated if total_evaluated else float("nan")
    print("\n" + "-" * 78)
    print(
        f"Overall retention accuracy: {total_correct}/{total_evaluated} "
        f"({overall:.1f}%)"
    )


def print_energy_summary(data: pd.DataFrame, specs: tuple[SystemSpec, ...]) -> None:
    print("\n" + "=" * 78)
    print("ENERGY AND RANKING SUMMARY")
    print("=" * 78)
    print(
        f"{'system':<10} {'n':>4}  {'abs MAE':>9} {'abs RMSE':>10}  "
        f"{'rel MAE':>9} {'rel RMSE':>10}  {'rank rho':>9}"
    )
    print("-" * 78)
    for spec in specs:
        subset = data[
            (data["system"] == spec.label)
            & data["DFT_Eads_eV"].notna()
            & data["M6_Eads_eV"].notna()
        ]
        if len(subset) < 2:
            print(f"{spec.label:8s}: n={len(subset)}")
            continue
        errors = subset["M6_Eads_eV"] - subset["DFT_Eads_eV"]
        rel_errors = subset["M6_rel_Eads_eV"] - subset["DFT_rel_Eads_eV"]
        rho, _ = spearmanr(subset["DFT_rank"], subset["M6_rank"])
        print(
            f"{spec.label:<10} {len(subset):>4d}  "
            f"{np.mean(np.abs(errors)):>8.3f}  "
            f"{np.sqrt(np.mean(np.square(errors))):>9.3f}  "
            f"{np.mean(np.abs(rel_errors)):>8.3f}  "
            f"{np.sqrt(np.mean(np.square(rel_errors))):>9.3f}  "
            f"{rho:>9.3f}"
        )
    print("\nEnergy errors are in eV; rank rho is the Spearman correlation.")


