def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent,
        help="directory containing the five Ni test-system folders",
    )
    args = parser.parse_args()
    root = args.root.resolve()

    frames: list[pd.DataFrame] = []
    for spec in SYSTEMS:
        frame, errors = process_system(root, spec)
        frames.append(frame)
        print(
            f"{spec.label}: processed {len(frame)} structure pairs; "
            f"skipped {len(errors)}"
        )
        if errors:
            print("  " + "\n  ".join(errors))

    data = pd.concat(frames, ignore_index=True)
    if data.empty:
        raise RuntimeError("No matched initial/optimized structure pairs were processed.")

    print_initial_filename_motif_check(data)
    print_retention_summary(data, SYSTEMS)
    paired = data.dropna(subset=["DFT_Eads_eV", "M6_Eads_eV"])
    if paired.empty:
        print("No paired DFT/M6 energies; skipping energy statistics and parity figures.")
        return
    print_energy_summary(data, SYSTEMS)
    print_lowest_dft_structures(data, SYSTEMS)
    plot_absolute_relative_combined(data, SYSTEMS, root)
    plot_rankings(data, SYSTEMS, root)


if __name__ == "__main__":
    main()
