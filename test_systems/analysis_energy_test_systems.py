def parity_limits(data: pd.DataFrame, x_column: str, y_column: str) -> tuple[float, float]:
    values = np.concatenate(
        [
            data[x_column].dropna().to_numpy(dtype=float),
            data[y_column].dropna().to_numpy(dtype=float),
        ]
    )
    low = float(values.min())
    high = float(values.max())
    padding = 0.05 * (high - low) if high > low else 0.05
    return low - padding, high + padding


def plot_validation(
    data: pd.DataFrame,
    specs: tuple[SystemSpec, ...],
    output_dir: Path,
    vertical: bool = False,
) -> None:
    paired = data.dropna(subset=["DFT_Eads_eV", "M6_Eads_eV"]).copy()
    if paired.empty:
        raise ValueError("No paired DFT/M6 energies are available for plotting")

    plt.rcParams.update(
        {
            "font.size": 15,
            "axes.labelsize": 18,
            "xtick.labelsize": 15,
            "ytick.labelsize": 15,
        }
    )
    figure_definitions = (
        (
            "DFT_Eads_eV",
            "M6_Eads_eV",
            r"DFT $\mathrm{E}_{\mathrm{ads}}$ (eV)",
            r"Predicted $\mathrm{E}_{\mathrm{ads}}$ (eV)",
            "model_validation_absolute",
            False,
        ),
        (
            "DFT_rel_Eads_eV",
            "M6_rel_Eads_eV",
            r"DFT $\Delta \mathrm{E}_{\mathrm{ads}}$ (eV)",
            r"Predicted $\Delta \mathrm{E}_{\mathrm{ads}}$ (eV)",
            "model_validation_relative",
            False,
        ),
        (
            "DFT_rank",
            "M6_rank",
            "DFT rank",
            "Predicted rank",
            "model_validation_rankings",
            True,
        ),
    )

    for x_column, y_column, x_label, y_label, filename, is_rank in figure_definitions:
        is_relative = filename == "model_validation_relative"
        if not vertical:
            # Horizontal plots are reduced substantially when assembled in the
            # paper/SI, so use the larger publication-scale styling for all
            # three quantities.
            # Matplotlib sizes markers and text in physical points, so they do
            # not grow automatically when the canvas is enlarged. Scale them
            # explicitly with the 30-inch-wide publication figure.
            marker_size = 265
            axis_label_size = 28
            tick_label_size = 24
        elif is_relative:
            marker_size = 135
            axis_label_size = 20
            tick_label_size = 17
        else:
            marker_size = 105
            axis_label_size = 18
            tick_label_size = 15
        if vertical:
            fig, axes = plt.subplots(len(specs), 1, figsize=(6.4, 6.4 * len(specs)))
        else:
            fig, axes = plt.subplots(1, len(specs), figsize=(6.8 * len(specs), 6.2))
        if len(specs) == 1:
            marker_size = 85
            axis_label_size = 16
            tick_label_size = 13
        axes = np.atleast_1d(axes)
        for axis, spec in zip(axes, specs):
            system_data = paired[paired["system"] == spec.label]
            axis.scatter(
                system_data[x_column],
                system_data[y_column],
                s=marker_size,
                color=spec.color,
                alpha=0.78,
                edgecolors="black",
                linewidths=0.9,
                zorder=3,
            )
            if is_rank:
                maximum_rank = int(
                    np.nanmax(
                        np.concatenate(
                            [system_data[x_column], system_data[y_column]]
                        )
                    )
                )
                # Leave enough space for the large paper-size markers at ranks
                # 1 and N so their edges are not clipped by the axes spines.
                rank_padding = max(1.5, 0.04 * maximum_rank)
                axis_limits = (1.0 - rank_padding, maximum_rank + rank_padding)
            else:
                axis_limits = parity_limits(system_data, x_column, y_column)

            axis.plot(axis_limits, axis_limits, "k--", lw=1.0, zorder=2)
            axis.set_xlim(axis_limits)
            axis.set_ylim(axis_limits)
            axis.set_aspect("equal", adjustable="box")
            axis.set_xlabel(x_label, fontsize=axis_label_size)
            axis.set_ylabel(y_label, fontsize=axis_label_size)
            axis.grid(True, alpha=0.22, zorder=1)
            axis.xaxis.set_major_locator(MaxNLocator(nbins=5, integer=is_rank))
            axis.yaxis.set_major_locator(MaxNLocator(nbins=5, integer=is_rank))
            if not is_rank:
                axis.xaxis.set_minor_locator(AutoMinorLocator(2))
                axis.yaxis.set_minor_locator(AutoMinorLocator(2))
            axis.tick_params(
                which="major",
                length=7,
                width=1.1,
                labelsize=tick_label_size,
            )
            axis.tick_params(which="minor", length=4, width=0.9)

        if vertical:
            # A fixed common left margin plus aligned labels keeps every
            # y-axis spine and y label on the same vertical guides.
            fig.align_ylabels(axes)
            fig.subplots_adjust(
                left=0.22,
                right=0.97,
                bottom=0.035,
                top=0.99,
                hspace=0.38,
            )
        else:
            # Preserve the original compact energy-plot layout. Rank labels
            # are narrower than energy tick labels, so a little extra padding
            # is needed to obtain the same visual separation between panels.
            fig.tight_layout(w_pad=4.0 if is_rank else 1.8)
        output_stem = output_dir / f"{filename}{'_v' if vertical else ''}"
        fig.savefig(output_stem.with_suffix(".pdf"), bbox_inches="tight")
        plt.close(fig)
        print(f"Saved figure: {output_stem.with_suffix('.pdf')}")


def plot_absolute_relative_combined(
    data: pd.DataFrame,
    specs: tuple[SystemSpec, ...],
    output_dir: Path,
) -> None:
    """Combine the five absolute and five relative parity panels in a 2x5 grid.

    Both rows use identical subplot geometry.  Y labels are explicitly aligned
    within each system column so differences in tick-label width cannot shift
    the labels between the absolute and relative panels.
    """
    paired = data.dropna(subset=["DFT_Eads_eV", "M6_Eads_eV"]).copy()
    if paired.empty:
        raise ValueError("No paired DFT/M6 energies are available for plotting")

    rows = (
        (
            "DFT_Eads_eV",
            "M6_Eads_eV",
            r"DFT $\mathrm{E}_{\mathrm{ads}}$ (eV)",
            r"Predicted $\mathrm{E}_{\mathrm{ads}}$ (eV)",
        ),
        (
            "DFT_rel_Eads_eV",
            "M6_rel_Eads_eV",
            r"DFT $\Delta \mathrm{E}_{\mathrm{ads}}$ (eV)",
            r"Predicted $\Delta \mathrm{E}_{\mathrm{ads}}$ (eV)",
        ),
    )

    marker_size = 90 if len(specs) == 1 else 265
    axis_label_size = 16 if len(specs) == 1 else 28
    tick_label_size = 13 if len(specs) == 1 else 24

    fig, axes = plt.subplots(2, len(specs), figsize=(7.2, 11.5) if len(specs) == 1 else (30.0, 13.2))
    axes = np.asarray(axes, dtype=object).reshape(2, len(specs))
    for row_index, (x_column, y_column, x_label, y_label) in enumerate(rows):
        for column_index, spec in enumerate(specs):
            axis = axes[row_index, column_index]
            system_data = paired[paired["system"] == spec.label]
            axis.scatter(
                system_data[x_column],
                system_data[y_column],
                s=marker_size,
                color=spec.color,
                alpha=0.78,
                edgecolors="black",
                linewidths=0.9,
                zorder=3,
            )
            axis_limits = parity_limits(system_data, x_column, y_column)
            # The absolute-energy Ni(100)-4x4 panel otherwise receives a
            # 0.15-eV automatic tick interval (-1.05, -0.90, ...), uniquely
            # producing two-decimal labels.  Use clean 0.2-eV ticks over a
            # rounded range so this panel matches the one-decimal typography
            # of the other absolute-energy panels.
            is_ni100_absolute = row_index == 0 and spec.folder == "Ni100_4x4"
            if is_ni100_absolute:
                axis_limits = (-1.1, -0.5)
            axis.plot(axis_limits, axis_limits, "k--", lw=1.0, zorder=2)
            axis.set_xlim(axis_limits)
            axis.set_ylim(axis_limits)
            axis.set_aspect("equal", adjustable="box")
            axis.set_xlabel(x_label, fontsize=axis_label_size)
            if column_index == 0:
                axis.set_ylabel(y_label, fontsize=axis_label_size)
                # Fixed relative label coordinate keeps both row labels aligned.
                axis.yaxis.set_label_coords(-0.25, 0.5)
            axis.grid(True, alpha=0.22, zorder=1)
            if is_ni100_absolute:
                major_ticks = np.arange(-1.1, -0.49, 0.2)
                axis.set_xticks(major_ticks)
                axis.set_yticks(major_ticks)
                axis.xaxis.set_major_formatter(
                    FuncFormatter(lambda value, _position: Formatter.fix_minus(f"{value:.1f}"))
                )
                axis.yaxis.set_major_formatter(
                    FuncFormatter(lambda value, _position: Formatter.fix_minus(f"{value:.1f}"))
                )
            else:
                axis.xaxis.set_major_locator(MaxNLocator(nbins=5))
                axis.yaxis.set_major_locator(MaxNLocator(nbins=5))
            axis.xaxis.set_minor_locator(AutoMinorLocator(2))
            axis.yaxis.set_minor_locator(AutoMinorLocator(2))
            axis.tick_params(
                which="major", length=7, width=1.1,
                labelsize=tick_label_size,
            )
            axis.tick_params(which="minor", length=4, width=0.9)

    # Equal GridSpec rows and a single hspace value give the two rows the same
    # height and separation everywhere across the five system columns.
    if len(specs) == 1:
        fig.subplots_adjust(left=0.26, right=0.96, bottom=0.08, top=0.97, hspace=0.25)
    else:
        fig.subplots_adjust(
            left=0.065, right=0.99, bottom=0.075,
            top=0.985, wspace=0.42, hspace=0.16,
        )
    fig.align_ylabels(axes[:, 0])

    output_stem = output_dir / "absolute_relative_energies"
    fig.savefig(output_stem.with_suffix(".pdf"), bbox_inches="tight")
    plt.close(fig)
    print(f"Saved figure: {output_stem.with_suffix('.pdf')}")


